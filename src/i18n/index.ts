const dicts = { ar, en }

export function format(s: string, vars?: Record<string, string | number>) {
  if (!vars) return s
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''))
}

export function useT() {
  const lang = useSettings((s) => s.lang)
  const d = dicts[lang]
  const t = (k: TKey, vars?: Record<string, string | number>) => format(d[k], vars)
  return { t, lang, num: (n: number) => formatNum(n, lang) }
}

export function formatNum(n: number, lang: 'ar' | 'en') {
  return lang === 'ar' ? n.toLocaleString('ar-EG') : n.toLocaleString('en-US')
}
